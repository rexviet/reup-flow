#!/usr/bin/env bash
# View HyperFrames Studio from outside the LAN without forwarding any router port and
# without exposing the system sshd.
#
#   scripts/remote-studio.sh start     create the restricted sshd, start it and an ngrok TCP tunnel (pm2)
#   scripts/remote-studio.sh url       print the ssh command to run on the machine you are viewing from
#   scripts/remote-studio.sh status
#   scripts/remote-studio.sh stop      stop both; nothing stays reachable from the internet
#
# What is exposed: a private sshd of this user on 127.0.0.1:2222, reached through ngrok. It
# accepts only the public key(s) you pass with --key (kept in ~/.ssh/studio-tunnel/authorized_keys),
# never a password, gives no shell (a plain `ssh` only prints the review link), and can only forward
# to the Studio (127.0.0.1:3002) and the review page (127.0.0.1:3310). The system sshd on port 22 is
# not involved. It needs no root.
#
#   scripts/remote-studio.sh start --key "ssh-rsa AAAA... comment"
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
DIR="$HOME/.ssh/studio-tunnel"
PORT=2222
APPS=(reup-studio-sshd reup-studio-tunnel)
ACTION="${1:-status}"; shift || true
KEY=""
while [ $# -gt 0 ]; do
  case "$1" in
    --key) KEY="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac
done
die() { echo "error: $*" >&2; exit 1; }

setup() {
  mkdir -p "$DIR" && chmod 700 "$DIR"
  [ -f "$DIR/host_ed25519" ] || ssh-keygen -q -t ed25519 -N "" -C studio-tunnel-host -f "$DIR/host_ed25519"
  if [ -n "$KEY" ]; then
    printf '%s\n' "$KEY" > "$DIR/new.pub"
    ssh-keygen -l -f "$DIR/new.pub" >/dev/null || { rm -f "$DIR/new.pub"; die "that is not a valid public key"; }
    body=$(awk '{print $2}' "$DIR/new.pub")
    if ! grep -qsF "$body" "$DIR/authorized_keys"; then
      # `restrict` turns every capability off; only forwarding to the two Studio ports is added back.
      # The one command a session may run prints the review link (see remote-studio-link.sh).
      printf 'restrict,port-forwarding,command="%s/scripts/remote-studio-link.sh",permitopen="127.0.0.1:3002",permitopen="127.0.0.1:3310" %s\n' \
        "$ROOT" "$(cat "$DIR/new.pub")" >> "$DIR/authorized_keys"
    fi
    rm -f "$DIR/new.pub"
  fi
  [ -s "$DIR/authorized_keys" ] || die "no key yet: pass --key \"ssh-rsa AAAA...\" (a PUBLIC key)"
  chmod 600 "$DIR/authorized_keys"
  cat > "$DIR/sshd_config" <<EOF
# Private, key-only, forward-only sshd for viewing Studio. Generated by scripts/remote-studio.sh.
Port $PORT
ListenAddress 127.0.0.1
HostKey $DIR/host_ed25519
PidFile $DIR/sshd.pid
AuthorizedKeysFile $DIR/authorized_keys
UsePAM no
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
PermitRootLogin no
AllowUsers $USER
AuthenticationMethods publickey
AllowTcpForwarding local
GatewayPorts no
PermitTTY no
X11Forwarding no
AllowAgentForwarding no
PermitTunnel no
MaxAuthTries 6
# Every connection comes from 127.0.0.1 (ngrok), so a scanner failing to log in would otherwise
# penalise the same source address as you.
PerSourcePenalties no
LoginGraceTime 20
LogLevel VERBOSE
EOF
  /usr/sbin/sshd -t -f "$DIR/sshd_config" || die "the sshd configuration is invalid"
}

pm2_status() {
  pm2 jlist 2>/dev/null | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const a=JSON.parse(s.slice(s.indexOf("[")));const x=a.find(y=>y.name===process.argv[1]);console.log(x?x.pm2_env.status:"stopped")})' "$1"
}

tunnel_address() {
  curl -fsS -m 5 http://127.0.0.1:4040/api/tunnels 2>/dev/null | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{const t=JSON.parse(s).tunnels.find(x=>x.public_url.startsWith("tcp://"));if(t)console.log(t.public_url.replace("tcp://",""))}catch{}})'
}

case "$ACTION" in
  start)
    command -v pm2 >/dev/null || die "pm2 is not installed"
    command -v ngrok >/dev/null || die "ngrok is not installed"
    # Already running: leave the tunnel alone. Restarting it drops live sessions and changes the
    # address, because free ngrok TCP addresses are random. A new key needs no restart: sshd reads
    # the key file on every login.
    if [ "$(pm2_status reup-studio-sshd)" = online ] && [ "$(pm2_status reup-studio-tunnel)" = online ] \
       && [ -n "$(tunnel_address || true)" ]; then
      [ -z "$KEY" ] || setup
      echo "already running; nothing restarted"
      "$0" url
      exit 0
    fi
    setup
    pm2 delete "${APPS[@]}" >/dev/null 2>&1 || true
    pm2 start /usr/sbin/sshd --name reup-studio-sshd --interpreter none -- -D -e -f "$DIR/sshd_config" >/dev/null
    sleep 2
    # Password logins must be refused before anything is made public.
    refused=$(ssh -p $PORT -o PreferredAuthentications=password -o PubkeyAuthentication=no \
      -o BatchMode=yes -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
      -o ConnectTimeout=5 "$USER@127.0.0.1" true 2>&1 || true)
    echo "$refused" | grep -q "Permission denied" || { pm2 delete reup-studio-sshd >/dev/null 2>&1; die "the private sshd did not answer as expected: $refused"; }
    echo "private sshd is up on 127.0.0.1:$PORT and refuses passwords"
    pm2 start ngrok --name reup-studio-tunnel --interpreter none -- tcp 127.0.0.1:$PORT --log=stdout >/dev/null
    addr=""
    for _ in $(seq 1 20); do addr=$(tunnel_address || true); [ -n "$addr" ] && break; sleep 1; done
    if [ -z "${addr:-}" ]; then
      pm2 logs reup-studio-tunnel --lines 15 --nostream 2>&1 | grep -viE "DEP0060|trace-deprecation" | tail -8
      pm2 delete "${APPS[@]}" >/dev/null 2>&1 || true
      die "ngrok did not open a TCP tunnel (see above); nothing is exposed"
    fi
    echo "tunnel open: $addr"
    "$0" url
    ;;
  url)
    addr=$(tunnel_address || true); [ -n "$addr" ] || die "no tunnel is open (scripts/remote-studio.sh start)"
    host=${addr%:*}; port=${addr##*:}
    echo "On the machine you are viewing from (needs the private key of the public key you gave):"
    echo "  ssh -N -p $port -L 3002:127.0.0.1:3002 -L 3310:127.0.0.1:3310 $USER@$host"
    echo "to get the review link (fresh grant), run the same ssh without -N and -L:"
    echo "  ssh -p $port $USER@$host"
    echo "then open that link in your browser while the -N -L tunnel is running"
    ;;
  stop)
    pm2 delete "${APPS[@]}" >/dev/null 2>&1 || true
    echo "stopped: the tunnel and the private sshd are gone"
    ;;
  status)
    for app in "${APPS[@]}"; do printf '%-22s %s\n' "$app" "$(pm2_status "$app")"; done
    addr=$(tunnel_address || true); echo "public address: ${addr:-none}"
    ;;
  *) echo "usage: $0 start|url|status|stop" >&2; exit 2 ;;
esac
